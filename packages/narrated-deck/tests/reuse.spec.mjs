import {test,expect} from '@playwright/test';
test('generic Vue consumer uses different nodes, axes and capacities without Slidev or TTS',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('button',{name:'Explore evidence'})).toHaveCount(0);
 await page.getByRole('button',{name:'Play narrated review'}).click();
 await expect.poll(()=>page.locator('audio').evaluate(a=>a.currentTime)).toBeGreaterThan(.05);
 await page.keyboard.press('Space');
 await expect(page.locator('.path-node')).toHaveCount(3);
 await expect(page.locator('.path-diagram')).toHaveAttribute('data-standing','COULD NOT BE EXCLUDED');
 await page.keyboard.press('ArrowRight');
 await expect(page.locator('.path-diagram')).toHaveAttribute('data-standing','CONFIRMED');
 await page.keyboard.press('ArrowRight');
 await expect(page.locator('.metrics-panel')).toHaveAttribute('aria-label',/00:10 to 00:50/);
 await expect.poll(()=>page.locator('audio').evaluate(a=>a.duration)).toBe(1.5);
 await page.locator('audio').evaluate(a=>a.currentTime=.75);
 await expect.poll(()=>page.locator('.draw-line').evaluate(el=>parseFloat(getComputedStyle(el).strokeDashoffset))).toBeCloseTo(.5,1);
 await page.keyboard.press('ArrowRight');await expect(page.locator('.finding')).toHaveCount(0);
 await page.keyboard.press('ArrowRight');await expect(page.locator('.finding')).toHaveText('02backlog: 40');
 await expect(page.locator('.excerpt')).toContainText('<safe text>');
 await page.keyboard.press('ArrowRight');await expect(page.locator('.miniature')).toHaveAttribute('data-standing','CONFIRMED');
 await page.keyboard.press('ArrowRight');await expect(page.locator('.chart-finding')).toContainText('Difference: 15');
 await page.keyboard.press('ArrowRight');
 await expect.poll(()=>page.locator('audio').evaluate(a=>a.duration)).toBe(1.5);
 await page.locator('audio').evaluate(a=>a.currentTime=.9);
 await expect(page.locator('.drop-count strong')).toHaveText(['80','0']);
 await page.keyboard.press('Space');
 await expect(page.getByRole('button',{name:'Replay'})).toBeVisible();
 await page.getByRole('button',{name:'Explore evidence'}).click();
 await expect(page.locator('.after-review pre')).toContainText('backlog: 40');
 expect(await page.locator('audio').evaluate(a=>a.paused)).toBe(true);
 await page.getByRole('button',{name:'Explore evidence'}).focus();
 await page.keyboard.press('Space');
 await expect(page.locator('.after-review pre')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Replay'})).toBeVisible();
 expect(await page.locator('audio').evaluate(a=>a.paused)).toBe(true);
 await page.getByRole('button',{name:'Replay'}).click();
 await expect(page.locator('.path-node')).toHaveCount(3);
 expect(errors).toEqual([]);
 await page.screenshot({path:'.qa/reuse.png'});
});
